"""
AgriNova AI — AI Service.

Orchestrates the AI conversation flow with persistent conversations
and farm-contextual awareness.

Phase 2 flow (conversation persistence):
  1. Load or create conversation.
  2. Load existing message history BEFORE adding the new message.
  3. Save the new user message to DB.
  4. Build LLM messages: system prompt + existing history + new user message.
  5. Call LLM provider.
  6. Save assistant response to DB.
  7. Update conversation title/timestamp.

Phase 3 additions (context engine):
  - Resolve farm_id from request / conversation with locking rules.
  - Build UnifiedContext via ContextService.
  - Format context via ContextFormatter.
  - Inject formatted context into the system prompt.

Farm locking rules:
  ┌─────────────────┬─────────────────┬────────────────────┐
  │ Conversation     │ Request          │ Result             │
  │ farm_id          │ farm_id          │                    │
  ├─────────────────┼─────────────────┼────────────────────┤
  │ A                │ A                │ ✅ use A            │
  │ A                │ B                │ ❌ 409 Conflict     │
  │ A                │ None             │ ✅ use A            │
  │ None             │ A                │ ✅ lock to A        │
  │ None             │ B                │ ✅ lock to B        │
  │ None             │ None             │ ✅ no farm context  │
  └─────────────────┴─────────────────┴────────────────────┘

On LLM failure:
  - The user message is persisted (useful for retry).
  - No assistant message is saved.
  - A normalized provider error is raised.

System prompt:
  - Generated by the prompt layer at request time.
  - NOT persisted as a conversation message.
"""

import logging

from sqlalchemy.ext.asyncio import AsyncSession

from app.ai.providers.base import AIMessage, BaseAIProvider
from app.ai.providers.gemini import GeminiProvider
from app.ai.providers.openrouter import OpenRouterProvider
from app.ai.providers.manager import AIProviderManager
from app.ai.prompts.system import AIRA_SYSTEM_PROMPT
from app.ai.schemas.chat import ChatRequest, ChatResponse
from app.ai.services.context_service import ContextService
from app.ai.services.context_formatter import format_context
from app.core.config import settings
from app.core.exceptions import ConflictException, NotFoundException
from app.models.conversation import Conversation, Message
from app.models.farm import Farm
from app.repositories.conversation_repo import ConversationRepository
from app.repositories.farm_repo import FarmRepository
